// Declaramos una variable llamada 'year' y le asignamos el valor booleano 'false'.
let year = false;

// Evaluamos si 'year' es diferente de 'true' (!=).
// Como 'year' es 'false', la condición (false != true) se cumple y es verdadera.
if (year != true) {
    // Imprimimos en la consola el texto "OK" ya que la condición anterior se cumplió.
    console.log("OK");
}