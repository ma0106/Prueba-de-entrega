// Declaramos una variable llamada 'randomNumber' con el valor booleano 'false'.
let randomNumber = false;

// Convertimos el valor booleano anterior en una cadena de texto (String) 
// usando la función String() y lo guardamos en una nueva variable llamada 'boolean'.
let boolean = String(randomNumber);

// Imprimimos en la consola el valor actual de la variable 'boolean' (que ahora será el texto "false").
console.log(boolean);